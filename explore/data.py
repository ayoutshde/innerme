def score(answers):
    totals = [0]*4
    for value,(axis, direction, _) in zip(answers, QUESTIONS, strict=True):
        totals[axis] += (value-4)*direction
    rows = []
    for total,(positive,negative,yes,no) in zip(totals, AXES):
        rows.append({"left":positive,"right":negative,"left_label":yes,"right_label":no,
                     "letter":positive if total >= 0 else negative,
                     "meaning":LETTERS[positive if total >= 0 else negative]["meaning"],
                     "balance":round(50 + total*50/15),
                     "percent":round(50 + abs(total)*50/15),"tied":total == 0})
    return "".join(r["letter"] for r in rows), rows

