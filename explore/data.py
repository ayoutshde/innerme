    partner = {"Гал": "Агаар", "Агаар": "Гал", "Шороо": "Ус", "Ус": "Шороо"}[element]
    same = [SIGNS[i][0] for i in ELEMENTS[element][1] if i != index]
    match = [SIGNS[i][0] for i in ELEMENTS[partner][1]]
    return {"element": element, "partner": partner, "same": same, "match": match}
